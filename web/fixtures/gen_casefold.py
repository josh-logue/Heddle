"""Writes web/src/core/casefoldTable.ts: the characters whose Python casefold() differs
from their lower case (ß -> ss, ς -> σ, ﬁ -> fi, Cherokee, ...). JavaScript has no
casefold, so core/pystr.ts lower-cases everything else and looks these up.

Run from the repository root: python web/fixtures/gen_casefold.py
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "core" / "casefoldTable.ts"


def js_string(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(ch):x}}}" for ch in s) + '"'


def main() -> None:
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if c.casefold() != c.lower():
            rows.append(f"  [0x{cp:x}, {js_string(c.casefold())}],")
    text = (
        "// Generated by web/fixtures/gen_casefold.py: do not edit.\n"
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n"
        "// Characters whose casefold() differs from their lower case.\n"
        "export const CASEFOLD_EXCEPTIONS: ReadonlyMap<number, string> = new Map([\n"
        + "\n".join(rows) + "\n]);\n"
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rows)} entries -> {OUT}")


if __name__ == "__main__":
    main()
